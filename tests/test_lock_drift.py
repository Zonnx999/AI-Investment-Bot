"""scripts/lock_drift.py — 서버 .venv ↔ requirements.lock 불일치 점검 (RVOPS-03, 오프라인)."""

from __future__ import annotations

from pathlib import Path

import scripts.lock_drift as ld

_ROOT = Path(__file__).resolve().parents[1]

LOCK = """# This file was autogenerated by uv
beautifulsoup4==4.15.0
    # via yfinance
libsql-experimental==0.0.55
    # via ai-investment-bot (pyproject.toml)
pandas==3.0.6 ; python_version >= "3.12"
Requests[socks]==2.33.0
--index-url https://example.invalid/simple
"""


def test_parse_lock_ignores_comments_and_normalizes_names():
    assert ld.parse_lock(LOCK) == {
        "beautifulsoup4": "4.15.0", "libsql-experimental": "0.0.55",
        "pandas": "3.0.6", "requests": "2.33.0",
    }
    assert ld.normalize("libsql_experimental") == ld.normalize("LibSQL.Experimental") == "libsql-experimental"


def test_find_drift_reports_mismatch_and_missing():
    pins = ld.parse_lock(LOCK)
    installed = {"beautifulsoup4": "4.15.0", "libsql-experimental": "0.0.55",
                 "pandas": "2.2.3"}.get                       # requests 미설치
    drift = ld.find_drift(pins, installed)
    assert drift == [("pandas", "3.0.6", "2.2.3"), ("requests", "2.33.0", None)]
    text = ld.format_drift(drift, len(pins))
    assert text.startswith("lock 불일치 2/4개") and "pandas lock 3.0.6 / 설치 2.2.3" in text
    assert "requests lock 2.33.0 / 설치 없음" in text
    assert ld.find_drift(pins, {k: v for k, v in pins.items()}.get) == []


def test_format_drift_caps_items():
    drift = [(f"p{i}", "1", "0") for i in range(12)]
    text = ld.format_drift(drift, 20)
    assert text.count(" lock 1 / 설치 0") == ld.MAX_SHOWN and text.endswith("외 4개")


def test_main_exit_codes(tmp_path, monkeypatch, capsys):
    lock = tmp_path / "requirements.lock"
    lock.write_text("pkg-a==1.0\n", encoding="utf-8")
    monkeypatch.setattr(ld, "_installed_version", lambda name: "1.0")
    assert ld.main([str(lock)]) == ld.EXIT_MATCH and capsys.readouterr().out == ""
    monkeypatch.setattr(ld, "_installed_version", lambda name: "0.9")
    assert ld.main([str(lock)]) == ld.EXIT_DRIFT
    assert "lock 불일치 1/1개 · pkg-a lock 1.0 / 설치 0.9" in capsys.readouterr().out
    assert ld.main([str(tmp_path / "none.lock")]) == ld.EXIT_MATCH     # 못 읽으면 경고만


def test_real_lock_parses_core_pins():
    pins = ld.parse_lock((_ROOT / "requirements.lock").read_text(encoding="utf-8"))
    for name in ("pandas", "numpy", "yfinance", "libsql-experimental"):
        assert name in pins


def test_autopull_runs_drift_check_before_up_to_date_exit():
    """autopull 이 '최신 — 조용히 종료' 전에 drift 점검을 부른다 (첫 배포가 구 autopull 이어도 감지)."""
    sh = (_ROOT / "scripts" / "server_autopull.sh").read_text(encoding="utf-8")
    body = sh[sh.index("main() {"):]
    assert "lock_drift_check" in body
    assert body.index("    lock_drift_check\n") < body.index('if [ "$remote_sha" = "$deployed_sha" ]')
    assert 'notify_once "lockdrift:' in sh
